-- =====================================================================
-- Historial completo de cambios (Hibernate Envers)
-- =====================================================================
-- Complementa V29 (quien/cuando fue la ULTIMA modificacion de cada
-- fila). Esto guarda ademas CADA version anterior de cada fila, para
-- las entidades de negocio mas sensibles -- ver Usuario, Activo,
-- OrdenMantenimiento, OrdenReprogramacion, OrdenRepuesto, Repuesto,
-- StockRepuesto, Proveedor, Bodega, Ubicacion, TipoActivo y
-- MovimientoInventario (todas marcadas @Audited en su entidad Java).
--
-- No se incluyeron ADREDE: RefreshToken/PasswordResetToken (tokens de
-- seguridad efimeros, no aportan valor auditar su historico),
-- SesionUsuario/HistorialEstadoActivo (ya son ellos mismos un log/
-- historial, auditarlos seria un historial de un historial),
-- Notificacion, LecturaTemperatura y Depreciacion/DepreciacionMensual
-- (series de tiempo/calculos que se insertan una vez y no se
-- modifican). PuntoControl/LecturaControl (modulo Control de Turno)
-- quedaron pendientes en esta migracion: ese modulo vivia en la rama
-- "graficos" todavia no fusionada a esta rama al momento de escribir
-- esto. PuntoControl se agrego despues en V34, una vez fusionada.
--
-- Como funciona: Hibernate Envers (@Audited en cada entidad, ver
-- RevisionInfo/RevisionInfoListener) escribe automaticamente una fila
-- nueva en la <tabla>_aud correspondiente en CADA insert/update/delete,
-- ademas de la fila normal en la tabla real. No hace falta tocar el
-- codigo de los servicios: es transparente, Hibernate lo intercepta a
-- nivel de sesion.
--
-- revtype: 0 = ADD (fila creada), 1 = MOD (fila modificada),
--          2 = DEL (fila eliminada; las columnas de negocio quedan con
--          el ultimo valor conocido antes del DELETE).
--
-- Las FK de relacion (ej. id_tipo_activo en activo_aud) se guardan
-- como BIGINT simple, SIN constraint de FK: a proposito, para no
-- bloquear un DELETE en la tabla real solo porque una fila _aud
-- historica todavia "apunta" a algo que ya no existe (el historial
-- debe sobrevivir aunque el dato referenciado se borre despues).
--
-- Todas las tablas nuevas de esta migracion (revision_info y las 12
-- _aud) quedan CON Row Level Security, mismo patron que V27: aunque
-- alguna pantalla futura de "ver historial" se olvide de filtrar por
-- empresa, Postgres mismo no devuelve filas de otra empresa. Se aplica
-- al final de este archivo, una vez creadas todas las tablas.

CREATE TABLE revision_info (
    rev BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revtstmp BIGINT,
    usuario_id BIGINT,
    empresa_id BIGINT
);

CREATE INDEX idx_revision_info_empresa ON revision_info (empresa_id);
CREATE INDEX idx_revision_info_usuario ON revision_info (usuario_id);

