-- =====================================================================
-- Row Level Security para revision_info + las 12 tablas _aud nuevas
-- =====================================================================
-- Mismo patron que V27, pero acotado a las tablas de esta migracion
-- (V27 ya corrio antes y no vuelve a aplicarse retroactivamente a
-- tablas creadas despues). Si en el futuro se @Audited una entidad
-- nueva (fuera de esta migracion), hay que repetir este mismo patron
-- para su _aud puntual.
DO $$
DECLARE
    tabla text;
BEGIN
    FOR tabla IN
        SELECT DISTINCT c.table_name
        FROM information_schema.columns c
        JOIN information_schema.tables t
          ON t.table_schema = c.table_schema
         AND t.table_name = c.table_name
         AND t.table_type = 'BASE TABLE'
        WHERE c.table_schema = 'public'
          AND c.column_name = 'empresa_id'
          AND (c.table_name = 'revision_info' OR c.table_name LIKE '%\_aud' ESCAPE '\')
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tabla);
        EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', tabla);

        EXECUTE format('DROP POLICY IF EXISTS empresa_isolation ON %I', tabla);

        EXECUTE format(
            'CREATE POLICY empresa_isolation ON %I
                USING (
                    current_setting(''app.bypass_rls'', true) = ''on''
                    OR empresa_id = NULLIF(current_setting(''app.current_empresa_id'', true), '''')::bigint
                )
                WITH CHECK (
                    current_setting(''app.bypass_rls'', true) = ''on''
                    OR empresa_id = NULLIF(current_setting(''app.current_empresa_id'', true), '''')::bigint
                )',
            tabla
        );
    END LOOP;
END $$;
